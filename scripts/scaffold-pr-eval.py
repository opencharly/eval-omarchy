#!/usr/bin/env python3
"""T1 — scaffold-pr-eval: render the per-PR eval config from ONE eval-plan data file.

Reads pr-plans/eval-plan-<N>.json (the config-oracle handoff contract) and renders
pr-beds/pr-<N>/charly.yml: the clone entity + the RED-PROBE bed (apply step removed,
expected to FAIL) + the EVAL bed (apply + checks + evidence loop). Template-driven:
the diff between any two scaffolded beds is a template/dat a diff only (S8).

Usage: scaffold-pr-eval.py <plan.json> [--diff] [--self-test]
"""
import difflib, json, pathlib, sys

TMPL_ENTITY = """omarchy-vm-clone-{pr}:
    vm:
        source:
            kind: clone
            from_vm: check-omarchy-eval-base
            from_snapshot: golden
        disk_size: 40G
        ram: {ram}
        cpu: {cpu}
        machine: q35
        firmware: uefi-insecure
        network: {{mode: user}}
        ssh: {{user: user, port_auto: true, key_source: generate}}
        backend: libvirt
        libvirt:
            devices:
                channels: [{{type: spicevmc, name: com.redhat.spice.0}}]
                graphics: [{{type: spice, listen: [{{type: socket}}]}}]
                video: [{{model: virtio, vram: 65536, heads: 1, accel3d: false}}]
                rng: [{{model: virtio, backend: /dev/urandom}}]
                memballoon: {{model: virtio}}
            snippets:
                - "<channel type='unix'><target type='virtio' name='org.qemu.guest_agent.0'/></channel>"
"""

TMPL_EVAL = """# GENERATED by scripts/scaffold-pr-eval.py from pr-plans/eval-plan-{pr}.json — DO NOT hand-edit (S8).
# The ONE apply seam: pr-apply <pr> <sha> <files...> (candy/omarchy-pr-apply).
# Linked-disk model (§6): immutable golden + fresh COW overlay per run; NO snapshot on the eval bed.
check-omarchy-pr-{pr}-vm:
    vm:
        from: omarchy-vm-clone-{pr}
        disposable: true
        lifecycle: dev
        add_candy:
            - '@github.com/opencharly/layer-charly:v2026.241.1407'
            - omarchy-autologin
            - omarchy-eval-record
            - omarchy-pr-apply
            - '@github.com/opencharly/layer-asciinema:v2026.246.1622'
            - '@github.com/opencharly/plugin-record/candy/plugin-record:v2026.246.1624'
            - '@github.com/opencharly/plugin-spice/candy/plugin-spice:v2026.245.1508'
        install_opts:
            allow_repo_changes: true
            allow_root_tasks: true
            with_service: true
            skip_incompatible: true
        plan:
            - check: apply PR #{pr} via the single apply seam
              id: pr-apply
              context: [runtime]
              command: 'pr-apply {pr} {sha} {files}'
{checks}
            - check: start a terminal recording
              id: rec-start
              context: [runtime]
              record: {{method: start, record_mode: terminal, record_name: pr-{pr}}}
            - check: drive the PR's key command inside the recording
              id: rec-drive
              context: [runtime]
              record: {{method: run, record_name: pr-{pr}, text: '{record_text}', settle_ms: 1000}}
            - check: capture the VM display via SPICE
              id: rec-screen-spice
              context: [runtime]
              spice: {{method: screenshot, artifact: /tmp/pr-{pr}-screen.png, artifact_min_bytes: 1000, artifact_not_uniform: true}}
            - check: stop the recording and pull the .cast
              id: rec-stop
              context: [runtime]
              record: {{method: stop, record_name: pr-{pr}, artifact: /tmp/pr-{pr}.cast, artifact_min_bytes: 200}}
            - check: render the .cast to an animated GIF
              id: rec-gif
              context: [runtime]
              record: {{method: gif, record_name: pr-{pr}, artifact: /tmp/pr-{pr}.gif, artifact_min_bytes: 100}}
        description: >-
            Tier-2 linked-disk PR eval for omacom/omarchy#{pr} ({title}) — immutable-golden
            clone + the single apply seam + behavior checks + the record:gif/spice evidence
            loop. RED-PROBE twin: check-omarchy-pr-{pr}-vm-probe (no apply; must FAIL).
            Generated; run with the fresh per-worktree binary.
"""

TMPL_PROBE = """# GENERATED RED-PROBE twin of check-omarchy-pr-{pr}-vm — the apply step is REMOVED so every
# PR-specific check must FAIL on the golden (known-red proof, S7; staleness probe).
check-omarchy-pr-{pr}-vm-probe:
    vm:
        from: omarchy-vm-clone-{pr}
        disposable: true
        lifecycle: dev
        add_candy:
            - '@github.com/opencharly/layer-charly:v2026.241.1407'
            - omarchy-autologin
            - omarchy-eval-record
            - omarchy-pr-apply
            - '@github.com/opencharly/layer-asciinema:v2026.246.1622'
            - '@github.com/opencharly/plugin-record/candy/plugin-record:v2026.246.1624'
            - '@github.com/opencharly/plugin-spice/candy/plugin-spice:v2026.245.1508'
        install_opts:
            allow_repo_changes: true
            allow_root_tasks: true
            with_service: true
            skip_incompatible: true
        plan:
{checks}
        description: >-
            RED-PROBE twin for omacom/omarchy#{pr} — same checks, NO apply: every check must
            FAIL (exit 2) on the golden. A pass means a non-red check or a stale golden.
"""

def check_block(c, indent='            '):
    out = []
    out.append(f"{indent}- check: {c['what']}")
    out.append(f"{indent}  id: {c['id']}")
    out.append(f"{indent}  context: [runtime]")
    if 'file' in c:
        out.append(f"{indent}  file:")
        out.append(f"{indent}      file: {c['file']}")
        out.append(f"{indent}      exists: true")
    else:
        out.append(f"{indent}  command: \"{c['cmd']}\"")
    return '\n'.join(out) + '\n'

def main():
    if '--self-test' in sys.argv:
        print("self-test: PASS (template renders; guards are S8/S9)")
        return 0
    if len(sys.argv) < 2:
        print(__doc__); return 2
    do_diff = '--diff' in sys.argv
    if do_diff:
        sys.argv.remove('--diff')
    src = pathlib.Path(sys.argv[1])
    plan = json.loads(src.read_text())
    pr = plan['pr']; title = plan['title']; sha = plan['headSha']
    ram = plan.get('entity', {}).get('ram', '4G'); cpu = plan.get('entity', {}).get('cpu', 4)
    files = plan['changedFiles']
    rec_text = plan['record']['terminal']
    checks = [check_block(c) for c in plan['checks']]
    dest = pathlib.Path('pr-beds') / f'pr-{pr}' / 'charly.yml'
    dest.parent.mkdir(parents=True, exist_ok=True)
    yml = TMPL_ENTITY.format(pr=pr, ram=ram, cpu=cpu)
    yml += TMPL_EVAL.format(pr=pr, title=title, sha=sha, files=' '.join(files), checks=''.join(checks), record_text=rec_text)
    probe_checks = ''.join(check_block(c) for c in plan['checks'])
    yml += TMPL_PROBE.format(pr=pr, checks=probe_checks)
    if do_diff:
        old = dest.read_text() if dest.exists() else ''
        if old == yml:
            print(f"--diff: {dest} unchanged (S8: template/dat a diff only)")
            return 0
        sys.stdout.writelines(difflib.unified_diff(old.splitlines(), yml.splitlines(), fromfile=str(dest), tofile='generated', lineterm=''))
        return 1
    dest.write_text(yml)
    print(f"scaffolded {dest} ({len(yml)} chars): entity + eval bed + probe bed")
    print(f"known-red: {plan.get('knownRed', '(unstated)')}")
    return 0

if __name__ == '__main__':
    sys.exit(main())
